"""Power analysis for the backtesting protocol.

Most research plans ask, "how do we reject false edges?" This script asks the
paired question: "if a real edge exists, how often would this protocol approve
it?" The answer matters because an over-strict protocol can produce false
negatives so frequently that "no edge found" becomes weak evidence.

The model is deliberately simple and dependency-free:

* estimated Sharpes are Normal around their true Sharpes;
* the five-year standard error is fixed at 0.45, matching the protocol's
  effective OOS uncertainty after using CPCV-style resampling rather than a
  single realised path;
* one candidate has a true positive Sharpe and the rest are null candidates;
* the protocol selects the best development estimate, then asks whether the
  selected candidate passes a fresh OOS gate.

Usage:
    python research/analysis/research_power.py > results/research_power.md

Reproducibility: fixed seed (see SEED). No external data and no third-party
packages.
"""

from __future__ import annotations

import math
import random
from dataclasses import dataclass
from statistics import NormalDist

SEED = 20260827
N_RUNS = 50_000
SHARPE_SE = 0.45
TRUE_SHARPES = (0.4, 0.6, 1.0)
SEARCH_TRIALS = (1, 10, 100, 1_000)

# A compact proxy for the full decision stack: OOS Sharpe must clear the hurdle
# implied by PSR/DSR-style evidence requirements and practical benchmark margin.
# This threshold is intentionally reported so future protocol changes can be
# tested by changing one number rather than rewriting the analysis narrative.
FRESH_OOS_ACCEPTANCE_SHARPE = 1.09

# Misapplied selection correction demonstration. This is not used as a real gate;
# it quantifies the bug: applying a search correction to a fresh OOS sample makes
# the acceptance threshold absurdly high.
MISAPPLIED_DSR_OOS_SHARPE = 2.90


@dataclass(frozen=True)
class PowerRow:
    true_sharpe: float
    single_candidate_power: float
    affordable_trials_at_10pct_power: int | None


@dataclass(frozen=True)
class SearchRow:
    true_sharpe: float
    trials: int
    selects_real_candidate: float
    approves_real_candidate: float


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def normal_tail(mean: float, threshold: float, se: float = SHARPE_SE) -> float:
    return 1.0 - NormalDist(mu=mean, sigma=se).cdf(threshold)


def simulate_search(true_sharpe: float, trials: int, rng: random.Random) -> SearchRow:
    """Estimate selection and approval power for one real candidate plus nulls."""
    real_selected = 0
    real_approved = 0
    null_count = max(0, trials - 1)

    for _ in range(N_RUNS):
        real_dev = rng.gauss(true_sharpe, SHARPE_SE)
        if null_count == 0:
            selected_probability = 1.0
        else:
            selected_probability = NormalDist(mu=0.0, sigma=SHARPE_SE).cdf(real_dev) ** null_count
        if rng.random() > selected_probability:
            continue

        real_selected += 1
        real_oos = rng.gauss(true_sharpe, SHARPE_SE)
        if real_oos > FRESH_OOS_ACCEPTANCE_SHARPE:
            real_approved += 1

    return SearchRow(
        true_sharpe=true_sharpe,
        trials=trials,
        selects_real_candidate=real_selected / N_RUNS,
        approves_real_candidate=real_approved / N_RUNS,
    )


def power_rows() -> list[PowerRow]:
    rows: list[PowerRow] = []
    for true_sharpe in TRUE_SHARPES:
        single_power = normal_tail(true_sharpe, FRESH_OOS_ACCEPTANCE_SHARPE)
        affordable = None
        for trials in range(1, 101):
            selection_prob = 1.0 if trials == 1 else approximate_real_selection_probability(true_sharpe, trials)
            if selection_prob * single_power >= 0.10:
                affordable = trials
            else:
                break
        rows.append(PowerRow(true_sharpe, single_power, affordable))
    return rows


def approximate_real_selection_probability(true_sharpe: float, trials: int) -> float:
    """Cheap deterministic approximation for scanning affordable trial counts."""
    # P(null estimate < real estimate) integrated over the real estimate. The
    # max of many nulls is approximated by the 1 - 1/trials quantile.
    if trials <= 1:
        return 1.0
    null_best = SHARPE_SE * NormalDist().inv_cdf(1.0 - 1.0 / trials)
    return normal_tail(null_best, threshold=true_sharpe, se=SHARPE_SE)


def print_report() -> None:
    rng = random.Random(SEED)

    print("# Research Protocol Power")
    print()
    print("*Generated by `research/analysis/research_power.py`. This file is generated;")
    print("re-run the script rather than editing it.*")
    print()
    print("## Question")
    print()
    print("If the search contains one genuinely edged candidate and the rest are worthless, ")
    print("how often does the protocol both select the real candidate and approve it on a fresh OOS check?")
    print()
    print("## Assumptions")
    print()
    print(f"- Runs: {N_RUNS:,}, seed: {SEED}.")
    print(f"- Sharpe estimate standard error: {SHARPE_SE:.2f}.")
    print(f"- Fresh OOS acceptance Sharpe proxy: {FRESH_OOS_ACCEPTANCE_SHARPE:.2f}.")
    print("- Development selection noise and OOS validation noise are independent.")
    print()
    print("## Power by true Sharpe")
    print()
    print("| True Sharpe | Power, single pre-specified candidate | Trials affordable at >=10% power |")
    print("|---:|---:|---:|")
    for row in power_rows():
        affordable = "none" if row.affordable_trials_at_10pct_power is None else str(row.affordable_trials_at_10pct_power)
        print(f"| {row.true_sharpe:.1f} | {_pct(row.single_candidate_power)} | {affordable} |")
    print()
    print("## Search penalty")
    print()
    print("| True Sharpe | Trials | P(real candidate selected) | P(real candidate approved) |")
    print("|---:|---:|---:|---:|")
    for true_sharpe in TRUE_SHARPES:
        for trials in SEARCH_TRIALS:
            row = simulate_search(true_sharpe, trials, rng)
            print(
                f"| {row.true_sharpe:.1f} | {row.trials:,} | "
                f"{_pct(row.selects_real_candidate)} | {_pct(row.approves_real_candidate)} |"
            )
    print()
    print("## Protocol implication")
    print()
    print("- The protocol is good at suppressing false positives, but it has low power at the Sharpe range")
    print("  V1 itself predicts. A failed V1 gate is therefore weak evidence against the mechanism unless")
    print("  the experiment was tightly pre-specified and the trial count stayed tiny.")
    print("- Larger searches are not free. They reduce the chance that the real candidate is even selected")
    print("  before the fresh OOS gate sees it.")
    print("- This supports the zero-fitted-parameter V1 design and argues for an append-only trial ledger")
    print("  before any parameter search is allowed to expand.")
    print()
    print("## DSR placement bug caught by this analysis")
    print()
    print("Selection-bias correction belongs where selection occurred: the development/selection sample.")
    print("Applying a Deflated Sharpe search correction again to a fresh OOS estimate double-counts the")
    print("penalty. In this calibration, the misapplied OOS gate would require an OOS Sharpe above")
    print(f"{MISAPPLIED_DSR_OOS_SHARPE:.2f}, which would reject practically every plausible crypto trend edge.")


if __name__ == "__main__":
    print_report()
