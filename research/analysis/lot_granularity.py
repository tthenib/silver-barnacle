"""Can the account actually express the position size the strategy asks for?

Position sizing math assumes continuous lot sizes. Brokers quantise to `lot_step`
with a `min_lot` floor. On a small account trading a high-notional instrument,
the *minimum legal position* can already carry more risk than the intended
per-trade budget -- in which case the strategy cannot be traded as designed, no
matter how good the signal is.

This is a deployment blocker that is invisible in a backtest run with continuous
lots, and it is cheaper to discover now than after the EA is written.

Usage:
    python research/analysis/lot_granularity.py > results/lot_granularity.md

No external data. Broker specs are illustrative and MUST be replaced with values
queried from the live symbol before any deployment decision.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

# --- Assumptions (illustrative; verify against the live symbol) --------------
# BTC daily ATR as a fraction of price. 3% is a mid-range figure for recent
# years; it has been both much higher and somewhat lower.
ATR_PCT_OF_PRICE = 0.03
BTC_PRICE = 60_000.0
BTC_ANN_VOL = 0.50          # annualised realised volatility
STOP_ATR_MULTIPLE = 4.0     # V1 catastrophe stop
TARGET_ANN_VOL = 0.15       # V1 strategy volatility target
GBP_USD = 1.27


@dataclass(frozen=True)
class SymbolSpec:
    name: str
    price: float
    contract_size: float     # units of base asset per 1.00 lot
    min_lot: float
    lot_step: float


# Crypto CFD specs vary widely between brokers. These three bracket what is
# commonly offered on retail MT5 crypto accounts.
BROKERS = [
    SymbolSpec("BTCUSD (coarse: 1 BTC/lot, min 0.01)", BTC_PRICE, 1.0, 0.01, 0.01),
    SymbolSpec("BTCUSD (fine:   1 BTC/lot, min 0.001)", BTC_PRICE, 1.0, 0.001, 0.001),
    SymbolSpec("BTCUSD (micro:  0.1 BTC/lot, min 0.01)", BTC_PRICE, 0.1, 0.01, 0.01),
]

ACCOUNT_SIZES_USD = [2_000 * GBP_USD, 5_000.0, 10_000.0, 25_000.0, 50_000.0]


def vol_target_lots(equity: float, spec: SymbolSpec) -> float:
    """Continuous lot size that targets TARGET_ANN_VOL on the account."""
    target_notional = equity * TARGET_ANN_VOL / BTC_ANN_VOL
    return target_notional / (spec.price * spec.contract_size)


def round_to_step(lots: float, spec: SymbolSpec) -> float:
    """Round DOWN to a legal lot size. Below min_lot means 'cannot trade'."""
    if lots < spec.min_lot:
        return 0.0
    steps = math.floor(lots / spec.lot_step + 1e-9)
    return round(steps * spec.lot_step, 8)


def stop_risk_pct(lots: float, equity: float, spec: SymbolSpec) -> float:
    """Loss as a fraction of equity if the catastrophe stop is hit exactly."""
    stop_distance = STOP_ATR_MULTIPLE * ATR_PCT_OF_PRICE * spec.price
    loss = lots * spec.contract_size * stop_distance
    return loss / equity


def main() -> None:
    print("# Lot Granularity vs. Account Size")
    print()
    print("*Generated by `research/analysis/lot_granularity.py`. This file is generated;")
    print("re-run the script rather than editing it.*")
    print()
    print(f"Assumptions: BTC = ${BTC_PRICE:,.0f}, daily ATR = {ATR_PCT_OF_PRICE:.0%} of price, ")
    print(f"annualised vol = {BTC_ANN_VOL:.0%}, V1 stop = {STOP_ATR_MULTIPLE:.0f} x ATR ")
    print(f"({STOP_ATR_MULTIPLE * ATR_PCT_OF_PRICE:.0%} of price), V1 vol target = {TARGET_ANN_VOL:.0%}.")
    print()
    print("`ideal lots` is what volatility targeting asks for. `actual lots` is what the")
    print("broker will accept. `stop risk` is the loss as a share of equity if the")
    print("catastrophe stop is hit at the actual size.")
    print()

    for spec in BROKERS:
        print(f"### {spec.name}")
        print()
        print("| Equity (USD) | Ideal lots | Actual lots | Quantisation error | Notional | Stop risk | Tradeable? |")
        print("|---|---|---|---|---|---|---|")
        for equity in ACCOUNT_SIZES_USD:
            ideal = vol_target_lots(equity, spec)
            actual = round_to_step(ideal, spec)
            if actual == 0.0:
                print(
                    f"| ${equity:,.0f} | {ideal:.4f} | 0 | -100% | - | - | "
                    f"**NO** - below min lot |"
                )
                continue
            err = actual / ideal - 1.0
            notional = actual * spec.contract_size * spec.price
            risk = stop_risk_pct(actual, equity, spec)
            verdict = "yes" if abs(err) < 0.25 and risk < 0.05 else "**degraded**"
            print(
                f"| ${equity:,.0f} | {ideal:.4f} | {actual:.4f} | {err:+.0%} | "
                f"${notional:,.0f} | {risk:.2%} | {verdict} |"
            )
        print()

    print("## Reading this")
    print()
    print("- **Quantisation error** is a permanent, uncompensated tracking error against the")
    print("  research backtest. Above roughly +/-25% the live system is not running the")
    print("  strategy that was validated.")
    print("- **Stop risk** above ~5% of equity on a single position means the catastrophe")
    print("  stop is no longer a catastrophe stop -- it is a routine account event.")
    print("- A 'NO' row means the strategy **cannot be traded as designed** on that account")
    print("  and broker. The options are a finer-granularity symbol, a different broker, a")
    print("  larger account, or a different instrument. Changing the *strategy* to fit the")
    print("  lot size is the wrong answer and must be recorded as such if it happens.")
    print()


if __name__ == "__main__":
    main()
